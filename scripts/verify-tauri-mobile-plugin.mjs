import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { cp, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const workspaceRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageDirectory = join(workspaceRoot, "packages/entity-graph-tauri");
const fixtureDirectory = join(workspaceRoot, "tests/fixtures/tauri-plugin-host");
const laneDocument = join(workspaceRoot, "release/tauri-mobile-device-lane.md");
const deviceEvidencePath = join(
  workspaceRoot,
  ".kbd-orchestrator/phases/full-3.0-release/evidence/v3-tauri-mobile-plugin/device/device-evidence.json",
);
const reportPath = option("--report");
const visualPath = option("--visual");
const temporaryRoot = await mkdtemp(join(tmpdir(), "prometheus-tauri-plugin-"));
const tarballDirectory = join(temporaryRoot, "tarballs");
const extractedDirectory = join(temporaryRoot, "candidate");
const packedHostDirectory = join(temporaryRoot, "packed-host");
const cargoTargetDirectory = join(fixtureDirectory, "target/verifier-cargo-target");
const cargoBuildDirectory = join(fixtureDirectory, "target/verifier-build-cache");

const report = {
  schemaVersion: 1,
  generatedAt: new Date().toISOString(),
  plugin: "@prometheus-ags/entity-graph-tauri",
  javascriptBindings: {
    rustDrift: "pending",
    typecheck: "pending",
    runtimeTests: "pending",
  },
  desktopHost: {
    realPluginCommand: "pending",
    platform: null,
    capabilityDenial: "pending",
  },
  packedConsumer: {
    dependencySource: "candidate-tarball-only",
    cargoTest: "pending",
    nativePayload: "pending",
    files: [],
  },
  mobileDeviceLane: {
    android: "pending",
    ios: "pending",
    command: "plugin:entity-graph-tauri|graph_platform_ping",
    executionEvidence: "pending",
    visualEvidence: "pending",
  },
};

try {
  await mkdir(tarballDirectory, { recursive: true });

  await run("cargo", [
    "+stable",
    "run",
    "--manifest-path",
    join(packageDirectory, "rust-plugin/Cargo.toml"),
    "--bin",
    "generate-bindings",
    "--features",
    "generate-bindings",
    "--",
    "--check",
  ]);
  report.javascriptBindings.rustDrift = "pass";
  await run("pnpm", ["--filter", "@prometheus-ags/entity-graph-tauri", "typecheck"]);
  report.javascriptBindings.typecheck = "pass";
  await run("pnpm", ["--filter", "@prometheus-ags/entity-graph-tauri", "test"]);
  report.javascriptBindings.runtimeTests = "pass";

  const sourceHost = await run("cargo", [
    "+1.88.0",
    "test",
    "--manifest-path",
    join(fixtureDirectory, "Cargo.toml"),
    "--locked",
    "--",
    "--nocapture",
  ], { env: { CARGO_TARGET_DIR: cargoTargetDirectory } });
  assertOutput(sourceHost, "registered_desktop_host_invokes_the_real_platform_command");
  assertOutput(sourceHost, "host_without_the_capability_denies_platform_ping");
  report.desktopHost.realPluginCommand = "pass";
  report.desktopHost.platform = "desktop";
  report.desktopHost.capabilityDenial = "pass";

  await run("pnpm", ["--filter", "@prometheus-ags/entity-graph-tauri", "build"]);
  const packed = await run("pnpm", [
    "--dir",
    packageDirectory,
    "pack",
    "--pack-destination",
    tarballDirectory,
    "--json",
  ]);
  const packResult = JSON.parse(packed.stdout);
  const tarballPath = resolve(packResult.filename);
  const files = packResult.files.map(({ path }) => path).sort();
  report.packedConsumer.files = files;

  const forbiddenPayloadPrefixes = [
    "rust-plugin/android/.gradle/",
    "rust-plugin/android/.tauri/",
    "rust-plugin/android/build/",
    "rust-plugin/ios/.build/",
    "rust-plugin/target/",
  ];
  const forbiddenPayload = files.filter((path) =>
    forbiddenPayloadPrefixes.some((prefix) => path.startsWith(prefix)),
  );
  if (forbiddenPayload.length > 0) {
    throw new Error(`packed Tauri candidate contains generated build state: ${forbiddenPayload[0]}`);
  }

  const requiredPayload = [
    "rust-plugin/Cargo.toml",
    "rust-plugin/build.rs",
    "rust-plugin/src/lib.rs",
    "rust-plugin/src/desktop.rs",
    "rust-plugin/src/mobile.rs",
    "rust-plugin/android/src/main/java/EntityGraphPlugin.kt",
    "rust-plugin/ios/Sources/EntityGraphPlugin.swift",
    "rust-plugin/permissions/default.toml",
    "rust-plugin/permissions/autogenerated/commands/graph_platform_ping.toml",
  ];
  for (const path of requiredPayload) {
    if (!files.includes(path)) throw new Error(`packed Tauri candidate is missing ${path}`);
  }
  if (files.includes("rust-plugin/Cargo.lock")) {
    throw new Error("packed Tauri candidate must not publish its development Cargo.lock");
  }
  await mkdir(extractedDirectory, { recursive: true });
  await run("tar", ["-xzf", tarballPath, "-C", extractedDirectory]);
  const packedRustPlugin = join(extractedDirectory, "package/rust-plugin");
  const packedAndroidPlugin = await readFile(
    join(packedRustPlugin, "android/src/main/java/EntityGraphPlugin.kt"),
    "utf8",
  );
  if (!packedAndroidPlugin.includes("@TauriPlugin")) {
    throw new Error("packed Android plugin is missing @TauriPlugin registration");
  }
  if (!packedAndroidPlugin.includes("fun ping(invoke: Invoke)")) {
    throw new Error("packed Android plugin is missing the native ping command");
  }
  const packedIosPlugin = await readFile(
    join(packedRustPlugin, "ios/Sources/EntityGraphPlugin.swift"),
    "utf8",
  );
  if (!packedIosPlugin.includes('@_cdecl("init_plugin_entity_graph_tauri")')) {
    throw new Error("packed iOS plugin is missing the Rust registration symbol");
  }
  if (!packedIosPlugin.includes("func initPlugin() -> Plugin")) {
    throw new Error("packed iOS plugin is missing the native initializer");
  }
  if (!packedIosPlugin.includes("func ping(_ invoke: Invoke)")) {
    throw new Error("packed iOS plugin is missing the native ping command");
  }
  report.packedConsumer.nativePayload = "pass";

  await cp(fixtureDirectory, packedHostDirectory, {
    recursive: true,
    filter: (source) => !source.endsWith("/target") && !source.includes("/target/"),
  });
  const consumerManifestPath = join(packedHostDirectory, "Cargo.toml");
  const consumerManifest = await readFile(consumerManifestPath, "utf8");
  const rewrittenManifest = consumerManifest.replace(
    /entity-graph-tauri = \{ path = "[^"]+" \}/,
    `entity-graph-tauri = { path = "${packedRustPlugin}" }`,
  );
  if (rewrittenManifest === consumerManifest) {
    throw new Error("packed host fixture dependency path was not rewritten");
  }
  await writeFile(consumerManifestPath, rewrittenManifest);
  await run("cargo", [
    "+1.88.0",
    "test",
    "--manifest-path",
    consumerManifestPath,
    "--locked",
    "--",
    "--nocapture",
  ], { env: { CARGO_TARGET_DIR: cargoTargetDirectory } });
  report.packedConsumer.cargoTest = "pass";

  const lane = await readFile(laneDocument, "utf8");
  for (const required of [
    "graphPlatformPing",
    "Android physical device",
    "iOS simulator or physical device",
    "platform-ping.json",
    "device-evidence.json",
    "hash-verified Android and iOS receipts",
  ]) {
    if (!lane.includes(required)) throw new Error(`mobile lane is missing: ${required}`);
  }

  const deviceEvidence = JSON.parse(await readFile(deviceEvidencePath, "utf8"));
  await validateDeviceEvidence(deviceEvidence);
  report.mobileDeviceLane.android = "pass-physical-device";
  report.mobileDeviceLane.ios = "pass-simulator";
  report.mobileDeviceLane.executionEvidence = "pass";
  report.mobileDeviceLane.visualEvidence = "pass";

  if (reportPath) await writeArtifact(reportPath, `${JSON.stringify(report, null, 2)}\n`);
  if (visualPath) await writeArtifact(visualPath, renderSvg(report));
  process.stdout.write(
    "[tauri-plugin] PASS: desktop IPC, packed Rust host, and hash-verified Android/iOS success and denial receipts.\n",
  );
} finally {
  await rm(temporaryRoot, { recursive: true, force: true });
}

function option(name) {
  const index = process.argv.indexOf(name);
  if (index < 0) return null;
  const value = process.argv[index + 1];
  if (!value) throw new Error(`${name} requires a file path`);
  return value;
}

async function run(command, args, options = {}) {
  const result = await execFileAsync(command, args, {
    cwd: options.cwd ?? workspaceRoot,
    env: {
      ...process.env,
      FORCE_COLOR: "0",
      CARGO_NET_OFFLINE: "true",
      CARGO_BUILD_BUILD_DIR: cargoBuildDirectory,
      ...options.env,
    },
    encoding: "utf8",
    maxBuffer: 30 * 1024 * 1024,
    timeout: 10 * 60 * 1_000,
  });
  process.stdout.write(result.stdout);
  process.stderr.write(result.stderr);
  return result;
}

function assertOutput(result, expected) {
  const output = `${result.stdout}\n${result.stderr}`;
  if (!output.includes(expected)) throw new Error(`host output is missing ${expected}`);
}

async function validateDeviceEvidence(evidence) {
  if (evidence.schemaVersion !== 1) throw new Error("unsupported mobile evidence schema");
  if (evidence.command !== report.mobileDeviceLane.command) {
    throw new Error("mobile evidence command does not match the generated binding contract");
  }

  const expected = {
    android: { targetKind: "physical-device", platform: "android" },
    ios: { targetKind: "simulator", platform: "ios" },
  };
  for (const [name, contract] of Object.entries(expected)) {
    const platform = evidence.platforms?.[name];
    if (!platform) throw new Error(`mobile evidence is missing ${name}`);
    if (platform.targetKind !== contract.targetKind) {
      throw new Error(`${name} evidence has the wrong target kind`);
    }
    const exactResponse = JSON.stringify({
      plugin: "entity-graph-tauri",
      platform: contract.platform,
    });
    if (JSON.stringify(platform.success?.response) !== exactResponse) {
      throw new Error(`${name} native response does not match ${exactResponse}`);
    }
    const denial = platform.denial?.error ?? "";
    if (!denial.includes("graph_platform_ping not allowed") || !denial.includes("entity-graph-tauri:default")) {
      throw new Error(`${name} capability denial is incomplete`);
    }

    for (const [outcome, receipt] of Object.entries({
      success: platform.success,
      denial: platform.denial,
    })) {
      if (!Array.isArray(receipt?.artifacts) || receipt.artifacts.length < 2) {
        throw new Error(`${name} ${outcome} evidence has too few artifacts`);
      }
      if (!receipt.artifacts.some(({ path }) => path.endsWith(".png"))) {
        throw new Error(`${name} ${outcome} evidence is missing a visual receipt`);
      }
      if (!receipt.artifacts.some(({ path }) => path.endsWith(".json"))) {
        throw new Error(`${name} ${outcome} evidence is missing a machine-readable receipt`);
      }
      for (const artifact of receipt.artifacts) {
        const absolutePath = resolve(workspaceRoot, artifact.path);
        if (!absolutePath.startsWith(`${workspaceRoot}/`)) {
          throw new Error(`mobile evidence path escapes the workspace: ${artifact.path}`);
        }
        const digest = createHash("sha256").update(await readFile(absolutePath)).digest("hex");
        if (digest !== artifact.sha256) {
          throw new Error(`mobile evidence hash mismatch: ${artifact.path}`);
        }
      }
    }
  }
}

async function writeArtifact(path, content) {
  const absolute = resolve(workspaceRoot, path);
  await mkdir(dirname(absolute), { recursive: true });
  await writeFile(absolute, content);
  process.stdout.write(`[tauri-plugin] wrote ${relative(workspaceRoot, absolute)}\n`);
}

function renderSvg(result) {
  const rows = [
    ["Rust-derived bindings", result.javascriptBindings.rustDrift],
    ["Desktop registered IPC", result.desktopHost.realPluginCommand],
    ["Capability denial", result.desktopHost.capabilityDenial],
    ["Packed Rust consumer", result.packedConsumer.cargoTest],
    ["Native payload", result.packedConsumer.nativePayload],
    ["Android physical device", result.mobileDeviceLane.android === "pass-physical-device" ? "pass" : "pending"],
    ["iOS simulator", result.mobileDeviceLane.ios === "pass-simulator" ? "pass" : "pending"],
  ];
  const renderedRows = rows.map(([label, status], index) => {
    const y = 174 + index * 43;
    const pass = status === "pass";
    const color = pass ? "#38d996" : "#f3b85b";
    return `<text x="72" y="${y}" fill="#dbe8ff" font-size="20">${label}</text><text x="840" y="${y}" text-anchor="end" fill="${color}" font-size="18" font-weight="700">${status.toUpperCase()}</text>`;
  }).join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="920" height="520" viewBox="0 0 920 520" role="img" aria-labelledby="title desc">
  <title id="title">Prometheus Tauri plugin verification</title>
  <desc id="desc">Desktop, packed-consumer, Android physical-device, and iOS simulator checks pass with hash-verified success and permission-denial receipts.</desc>
  <rect width="920" height="520" rx="28" fill="#081426"/>
  <rect x="28" y="28" width="864" height="464" rx="20" fill="#0e213c" stroke="#285078"/>
  <text x="72" y="88" fill="#38d996" font-size="18" font-weight="700" letter-spacing="2">PROMETHEUS 3.0</text>
  <text x="72" y="126" fill="#ffffff" font-size="30" font-weight="700">Tauri plugin host contract</text>
  ${renderedRows}
  <text x="72" y="482" fill="#91a8c8" font-size="14">Generated from machine-readable verification · ${result.generatedAt}</text>
</svg>\n`;
}
