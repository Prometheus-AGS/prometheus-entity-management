import {
  PACKAGE_BUGS_URL,
  PACKAGE_ENTRYPOINT_CONTRACT,
  PACKAGE_NODE_ENGINE,
  PACKAGE_REPOSITORY_URL,
} from "./public-packages.mjs";

export function validateManifest(publicPackage, manifest) {
  assert(manifest.name === publicPackage.name, `${publicPackage.directory}: wrong package name`);
  assert(manifest.private !== true, `${publicPackage.name}: public package cannot be private`);
  assert(manifest.type === "module", `${publicPackage.name}: type must be module`);
  assert(manifest.main === PACKAGE_ENTRYPOINT_CONTRACT.main, `${publicPackage.name}: invalid main`);
  assert(manifest.module === PACKAGE_ENTRYPOINT_CONTRACT.module, `${publicPackage.name}: invalid module`);
  assert(manifest.types === PACKAGE_ENTRYPOINT_CONTRACT.types, `${publicPackage.name}: invalid types`);
  assert(
    JSON.stringify(manifest.exports?.["."]) ===
      JSON.stringify(PACKAGE_ENTRYPOINT_CONTRACT.exports),
    `${publicPackage.name}: conditional exports do not match the release contract`,
  );
  assert(manifest.author, `${publicPackage.name}: author is required`);
  assert(manifest.license === "MIT", `${publicPackage.name}: license must be MIT`);
  assert(manifest.engines?.node === PACKAGE_NODE_ENGINE, `${publicPackage.name}: invalid Node engine`);
  assert(manifest.repository?.url === PACKAGE_REPOSITORY_URL, `${publicPackage.name}: invalid repository URL`);
  assert(
    manifest.repository?.directory === publicPackage.directory,
    `${publicPackage.name}: invalid repository directory`,
  );
  assert(manifest.bugs?.url === PACKAGE_BUGS_URL, `${publicPackage.name}: invalid bugs URL`);
  assert(typeof manifest.homepage === "string", `${publicPackage.name}: homepage is required`);
  assert(manifest.files?.includes("dist"), `${publicPackage.name}: dist must be packed`);
  assert(manifest.files?.includes("README.md"), `${publicPackage.name}: README must be packed`);
  assert(manifest.files?.includes("CHANGELOG.md"), `${publicPackage.name}: changelog must be packed`);
}

export function validateTarballFileList(publicPackage, files) {
  for (const required of [
    "package.json",
    "README.md",
    "CHANGELOG.md",
    "dist/index.mjs",
    "dist/index.cjs",
    "dist/index.d.ts",
    "dist/index.d.cts",
  ]) {
    assert(files.includes(required), `${publicPackage.name}: tarball is missing ${required}`);
  }

  const forbidden = files.filter(
    (file) =>
      file.includes("node_modules/") ||
      file.includes(".env") ||
      file.startsWith("src/") ||
      file === "rust-plugin/Cargo.lock",
  );
  assert(
    forbidden.length === 0,
    `${publicPackage.name}: unintended tarball files: ${forbidden.join(", ")}`,
  );

  const allowedPackageFiles = new Set(["package.json", "README.md", "CHANGELOG.md"]);
  const unexpected = files.filter((file) => {
    if (allowedPackageFiles.has(file) || file.startsWith("dist/")) return false;
    if (publicPackage.directory !== "packages/entity-graph-tauri") return true;
    return !(
      file === "rust-plugin/Cargo.toml" ||
      file === "rust-plugin/build.rs" ||
      file.startsWith("rust-plugin/src/") ||
      file.startsWith("rust-plugin/gen/schemas/") ||
      file === "rust-plugin/permissions/default.toml" ||
      /^rust-plugin\/permissions\/autogenerated\/commands\/[a-z0-9_-]+\.toml$/.test(file) ||
      file === "rust-plugin/permissions/autogenerated/reference.md" ||
      file === "rust-plugin/permissions/schemas/schema.json" ||
      file === "rust-plugin/android/build.gradle.kts" ||
      file === "rust-plugin/android/consumer-rules.pro" ||
      file === "rust-plugin/android/proguard-rules.pro" ||
      file === "rust-plugin/android/settings.gradle" ||
      file === "rust-plugin/android/src/main/AndroidManifest.xml" ||
      file === "rust-plugin/android/src/main/java/EntityGraphPlugin.kt" ||
      file === "rust-plugin/ios/Package.resolved" ||
      file === "rust-plugin/ios/Package.swift" ||
      file === "rust-plugin/ios/Sources/EntityGraphPlugin.swift"
    );
  });
  assert(
    unexpected.length === 0,
    `${publicPackage.name}: files are outside the intentional payload: ${unexpected.join(", ")}`,
  );
}

export function validatePackedManifestData(packedManifest, workspaceRoot) {
  const serialized = JSON.stringify(packedManifest);
  assert(!serialized.includes("workspace:"), `${packedManifest.name}: workspace protocol leaked into tarball`);
  assert(!serialized.includes("file:/"), `${packedManifest.name}: absolute file dependency leaked into tarball`);
  assert(!serialized.includes(workspaceRoot), `${packedManifest.name}: workspace path leaked into tarball`);
  assert(
    !/(?:\/Users\/|\/home\/|[A-Za-z]:\\Users\\)/.test(serialized),
    `${packedManifest.name}: local developer path leaked into tarball`,
  );
}

