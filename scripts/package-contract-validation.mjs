      jsdom: "^30.0.1",
      "loro-crdt": "1.13.9",
      lit: ">=3.0.0",
      react: ">=19.0.0 <20.0.0",
      "react-dom": ">=19.0.0 <20.0.0",
      "solid-js": ">=1.8.0",
      svelte: ">=5.0.0",
      typescript: "6.0.2",
      "y-webrtc": ">=10.2.3",
      "y-websocket": ">=2.0.4",
